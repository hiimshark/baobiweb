function serveStatic(req, res, pathname) {
  if (pathname === "/admin") {
    res.writeHead(302, { Location: "/admin/" });
    res.end();
    return;
  }
  if (pathname === "/admin/" || pathname.startsWith("/admin/")) {
    if (fs.existsSync(ADMIN_DIST)) {
      let sub = pathname.slice("/admin/".length);
      try {
        sub = decodeURIComponent(sub);
      } catch {}
      let resolved = path.resolve(ADMIN_DIST, sub);
      if (!resolved.startsWith(ADMIN_DIST)) {
        res.writeHead(403, SECURITY_HEADERS);
        res.end("Forbidden");
        return;
      }
      try {
        if (!fs.existsSync(resolved) || fs.statSync(resolved).isDirectory()) {
          resolved = path.join(ADMIN_DIST, "index.html");
        }
      } catch {
        resolved = path.join(ADMIN_DIST, "index.html");
      }
      const ext = path.extname(resolved).toLowerCase();
      const isImage = [".jpg", ".jpeg", ".png", ".webp", ".svg", ".ico"].includes(ext);
      res.writeHead(
        200,
        Object.assign(
          {
            "Content-Type": MIME[ext] || "application/octet-stream",
            "Cache-Control": isImage ? "public, max-age=604800" : "no-cache",
          },
          SECURITY_HEADERS,
        ),
      );
      if (req.method === "HEAD") {
        res.end();
        return;
      }
      fs.createReadStream(resolved).pipe(res);
      return;
    }
  }

  let rel = pathname;
  if (rel === "/" || rel === "/index.html") rel = "/index.html";
  else if (rel === "/quan-tri" || rel === "/quan-tri/") rel = "/quan-tri.html";
  try {
    rel = decodeURIComponent(rel);
  } catch {
    res.writeHead(400, SECURITY_HEADERS);
    res.end("Bad request");
    return;
  }
  if (rel.includes("\0")) {
    res.writeHead(400, SECURITY_HEADERS);
    res.end("Bad request");
    return;
  }
  const resolved = path.resolve(PUBLIC, "." + rel);
  if (resolved !== PUBLIC && !resolved.startsWith(PUBLIC + path.sep)) {
    res.writeHead(403, SECURITY_HEADERS);
    res.end("Forbidden");
    return;
  }
  fs.stat(resolved, (err, stat) => {
    if (err || !stat.isFile()) return serve404(res);
    const ext = path.extname(resolved).toLowerCase();
    const isImage = [".jpg", ".jpeg", ".png", ".webp", ".svg", ".ico"].includes(
      ext,
    );
    res.writeHead(
      200,
      Object.assign(
        {
          "Content-Type": MIME[ext] || "application/octet-stream",
          "Cache-Control": isImage ? "public, max-age=604800" : "no-cache",
        },
        SECURITY_HEADERS,
      ),
    );
    if (req.method === "HEAD") {
      res.end();
      return;
    }
    fs.createReadStream(resolved).pipe(res);
  });
}

