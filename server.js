function tooMany(ip, key, limit, windowMs) {
  const id = key + ":" + ip;
  const now = Date.now();
  let rec = hits.get(id);
  if (!rec || rec.reset < now) {
    rec = { count: 0, reset: now + windowMs };
    hits.set(id, rec);
  }
  rec.count += 1;
  return rec.count > limit;
}

function clearHits(ip, key) {
  hits.delete(key + ":" + ip);
}

