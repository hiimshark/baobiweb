function extractChats(updates) {
  const map = new Map();
  for (const update of updates || []) {
    const chat =
      (update.message && update.message.chat) ||
      (update.edited_message && update.edited_message.chat) ||
      (update.channel_post && update.channel_post.chat) ||
      (update.my_chat_member && update.my_chat_member.chat) ||
      (update.chat_member && update.chat_member.chat);
    if (!chat || chat.id == null) continue;
    const title =
      chat.title ||
      [chat.first_name, chat.last_name].filter(Boolean).join(" ") ||
      (chat.username ? "@" + chat.username : String(chat.id));
    map.set(String(chat.id), {
      id: String(chat.id),
      type: chat.type || "",
      title,
      username: chat.username || "",
    });
  }
  return Array.from(map.values());
}

