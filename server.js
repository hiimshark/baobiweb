function readOrders(limit) {
  if (!fs.existsSync(ORDERS_PATH)) return [];
  const lines = fs
    .readFileSync(ORDERS_PATH, "utf8")
    .split("\n")
    .filter(Boolean);
  return lines
    .slice(-limit)
    .reverse()
    .map((line) => {
      try {
        return JSON.parse(line);
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

