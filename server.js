function normalizeToken(raw) {
  let token = clean(raw, 200).replace(/\s+/g, "");
  token = token.replace(/^https?:\/\/api\.telegram\.org\/bot/i, "");
  token = token.replace(/\/.*$/, "");
  if (/^bot\d+/i.test(token)) token = token.slice(3);
  return token;
}

function validToken(token) {
  return /^\d{5,}:[A-Za-z0-9_-]{10,}$/.test(token);
}

function maskToken(token) {
  if (!token) return "";
  if (token.length < 14) return "••••";
  return token.slice(0, 7) + "…" + token.slice(-4);
}

async function tg(token, method, payload) {
  if (!validToken(token)) {
    const err = new Error("Token bot chưa đúng định dạng.");
    err.status = 400;
    throw err;
  }
  const url = "https://api.telegram.org/bot" + token + "/" + method;
  let res;
  try {
    res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload || {}),
      signal: AbortSignal.timeout(15000),
    });
  } catch {
    const err = new Error(
      "Không gọi được Telegram. Kiểm tra mạng của máy chủ.",
    );
    err.status = 502;
    throw err;
  }
  const data = await res.json().catch(() => ({}));
  if (!res.ok || data.ok === false) {
    const err = new Error(
      translateTg(data.description, data.error_code, res.status),
    );
    err.status = Number.isInteger(data.error_code)
      ? data.error_code
      : res.status;
    err.description = data.description || "";
    throw err;
  }
  return data;
}

function translateTg(description, code, status) {
  const d = String(description || "");
  const low = d.toLowerCase();
  if (code === 401 || low.includes("unauthorized"))
    return "Token bot không dùng được. Hãy copy lại token từ BotFather.";
  if (code === 409 || low.includes("webhook"))
    return "Bot đang gắn webhook nên chưa đọc được hội thoại. Dán chat ID bằng tay, hoặc bấm tạm tắt webhook.";
  if (low.includes("chat not found"))
    return "Không thấy chat ID này. Hãy nhắn tin cho bot trước, rồi tìm lại chat ID.";
  if (low.includes("blocked"))
    return "Bot đã bị chặn. Mở Telegram, bỏ chặn bot rồi gửi lại.";
  if (low.includes("not enough rights"))
    return "Bot chưa có quyền gửi tin trong nhóm. Hãy cho bot quyền gửi tin nhắn.";
  if (!d) return "Telegram không nhận yêu cầu (mã " + status + ").";
  return "Telegram báo: " + d;
}

