function parseItems(raw) {
  if (!Array.isArray(raw) || !raw.length || raw.length > 30) return null;
  const units = new Set(["kg", "cái", "xấp", "bộ", "mẫu"]);
  const items = [];
  for (const row of raw) {
    if (!row || typeof row !== "object") return null;
    const qty = Number(row.qty);
    const unit = clean(row.unit, 12);
    if (!Number.isFinite(qty) || qty <= 0 || qty > 1000000) return null;
    if (!units.has(unit)) return null;
    const name = clean(row.name, 120);
    if (name.length < 2) return null;
    items.push({
      id: clean(row.id, 40),
      name,
      size: clean(row.size, 80),
      color: clean(row.color, 40),
      spec: clean(row.spec, 40),
      specLabel: clean(row.specLabel, 40),
      extra: clean(row.extra, 40),
      extraLabel: clean(row.extraLabel, 40),
      qty,
      unit,
    });
  }
  return items;
}

